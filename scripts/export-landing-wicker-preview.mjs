#!/usr/bin/env node
/**
 * Capture Wicker Park demo analyze JSON for the landing report preview (no live Qloo).
 * Prereq: worker on APP_MODE=demo (see scripts/run-record-demo.mjs).
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const WORKER = process.env.PLAYWRIGHT_API_URL || 'http://127.0.0.1:8792';
const ADDRESS = '1574 N Milwaukee Ave, Chicago, IL 60622';

const res = await fetch(`${WORKER}/api/analyze`, {
  method: 'POST',
  headers: { 'Content-Type': 'application/json' },
  body: JSON.stringify({ address: ADDRESS, radius: 10, storefrontSqFt: 2500 }),
});

if (!res.ok) {
  const text = await res.text();
  throw new Error(`analyze failed ${res.status}: ${text.slice(0, 500)}`);
}

const results = await res.json();
const outPath = join(process.cwd(), 'apps/web/src/data/landing-wicker-preview.ts');
const ts = `import type { AnalysisResponse } from '@leaseup/contracts';

/** Recorded demo analyze for Wicker Park (generated by scripts/export-landing-wicker-preview.mjs). */
export const LANDING_WICKER_PREVIEW: AnalysisResponse = ${JSON.stringify(results, null, 2)} as AnalysisResponse;

export const LANDING_WICKER_RADIUS_KM = 10;
export const LANDING_WICKER_SLUG = 'wicker';
`;

writeFileSync(outPath, ts, 'utf8');
console.log('Wrote', outPath, 'prospects:', results.prospects?.length ?? 0);
