import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
let gitSha = 'unknown';
try {
  gitSha = execSync('git rev-parse --short HEAD', { cwd: root, encoding: 'utf8' }).trim();
} catch {
  gitSha = process.env.GIT_SHA || 'unknown';
}

const buildTime = process.env.BUILD_TIME || new Date().toISOString();

const out = join(root, 'apps/worker/src/build-meta.ts');
const contents = `/** Generated by scripts/generate-build-meta.mjs — do not edit. */
export const BUILD_GIT_SHA = ${JSON.stringify(gitSha)};
export const BUILD_TIME = ${JSON.stringify(buildTime)};
`;

writeFileSync(out, contents);
console.log(`Wrote build meta ${gitSha} @ ${buildTime}`);
