#!/usr/bin/env node
/**
 * Embed demo store JSON as a TypeScript module (wrangler/esbuild-safe, no import attributes).
 */
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const root = join(scriptDir, '..');
const jsonPath = join(root, 'packages/fixtures/src/store-locations.json');
const outPath = join(root, 'packages/fixtures/src/store-locations-data.ts');
const data = JSON.parse(readFileSync(jsonPath, 'utf8'));

writeFileSync(
  outPath,
  `/* eslint-disable */\n/** Auto-generated by scripts/embed-demo-stores.mjs — do not edit. */\nexport const storeLocationsEmbedded = ${JSON.stringify(data)};\n`
);
console.log('Wrote', outPath);
