/**
 * Embed Schibsted Grotesk woff2 bytes for worker OG rendering (Resvg fontBuffers).
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fontDir = join(root, 'apps/worker/src/og/fonts');
const out = join(root, 'apps/worker/src/og/share-font-data.ts');

function embed(weight) {
  const path = join(fontDir, `schibsted-grotesk-latin-${weight}-normal.woff2`);
  const buf = readFileSync(path);
  return `new Uint8Array([${Array.from(buf).join(',')}])`;
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `/** Generated by scripts/embed-og-fonts.mjs — do not edit. */\n` +
    `export const SHARE_FONT_400 = ${embed(400)};\n` +
    `export const SHARE_FONT_600 = ${embed(600)};\n`
);
console.log('Wrote', out);
