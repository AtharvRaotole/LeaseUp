/**
 * Record brand-reverse heatmap fixture from live Qloo API.
 * Usage: QLOO_API_KEY=... node scripts/record-brand-reverse-fixture.mjs
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const key = process.env.QLOO_API_KEY;
if (!key) {
  console.error('Set QLOO_API_KEY');
  process.exit(1);
}

const brandId = '54617D9D-5EC7-45E0-8B7F-360DADB0FE7E';
const lat = 41.8781;
const lon = -87.6298;
const radiusM = 35000;

const url =
  `https://hackathon.api.qloo.com/v2/insights?filter.type=urn:heatmap` +
  `&filter.location=POINT(${lon}%20${lat})` +
  `&filter.location.radius=${radiusM}` +
  `&signal.interests.entities=${brandId}`;

const res = await fetch(url, {
  headers: { 'X-Api-Key': key, Accept: 'application/json' },
});
const text = await res.text();
if (!res.ok) {
  console.error('Qloo error', res.status, text.slice(0, 500));
  process.exit(1);
}

const data = JSON.parse(text);
const raw = data.results?.heatmap ?? [];
const cells = [];
for (const cell of raw) {
  const latitude = cell.location?.lat ?? cell.location?.latitude ?? cell.latitude;
  const longitude = cell.location?.lon ?? cell.location?.longitude ?? cell.longitude;
  if (latitude === undefined || longitude === undefined) continue;
  cells.push({
    latitude,
    longitude,
    affinity_rank: cell.query?.affinity_rank ?? cell.affinity_rank ?? 0,
    affinity: cell.query?.affinity ?? cell.affinity,
  });
}

const out = `/** Auto-generated by scripts/record-brand-reverse-fixture.mjs */
export type BrandReverseDemoFixture = {
  brandEntityId: string;
  metroId: string;
  source: 'heatmap' | 'grid_insights';
  sourceNote?: string;
  cells: Array<{
    latitude: number;
    longitude: number;
    affinity_rank: number;
    affinity?: number;
  }>;
};

export const brandReverseChicagoDemo: BrandReverseDemoFixture = ${JSON.stringify(
  {
    brandEntityId: brandId,
    metroId: 'chicago',
    source: 'heatmap',
    sourceNote: 'Recorded Qloo heatmap for Bath & Body Works in Chicago.',
    cells,
  },
  null,
  2
)};
`;

const target = join(process.cwd(), 'packages/fixtures/src/brand-reverse-chicago.ts');
writeFileSync(target, out);
console.log('Wrote', target, 'cells:', cells.length);
